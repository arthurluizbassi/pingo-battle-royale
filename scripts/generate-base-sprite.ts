/**
 * Generates src/sprites/data/base.ts (the Pingo body) from a few shape spans.
 * Run: npx tsx scripts/generate-base-sprite.ts
 * You can also hand-edit the generated grid afterwards; the game only reads the grid.
 *
 * Legend: '.' empty, '0' outline, '1' body, '2' shade, '3' highlight
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const SIZE = 40;
type Mask = boolean[][];
const newMask = (): Mask => Array.from({ length: SIZE }, () => Array(SIZE).fill(false));
const fill = (mask: Mask, y: number, x0: number, x1: number) => {
  for (let x = x0; x <= x1; x++) mask[y][x] = true;
};

// droplet body
const body = newMask();
const spans: Record<number, [number, number]> = {
  9: [19, 20], 10: [18, 21], 11: [17, 22], 12: [15, 24], 13: [13, 26],
  14: [12, 27], 15: [11, 28], 16: [11, 28], 32: [11, 28], 33: [12, 27], 34: [14, 25],
};
for (let y = 17; y <= 31; y++) spans[y] = [10, 29];
for (const [y, [x0, x1]] of Object.entries(spans)) fill(body, Number(y), x0, x1);

// feet (drawn behind the body)
const feet = newMask();
for (let y = 33; y <= 36; y++) {
  fill(feet, y, y === 36 ? 13 : 12, y === 36 ? 16 : 17);
  fill(feet, y, y === 36 ? 23 : 22, y === 36 ? 26 : 27);
}

// arms (drawn behind the body)
const arms = newMask();
for (let y = 23; y <= 26; y++) {
  const inset = y === 23 || y === 26 ? 1 : 0;
  fill(arms, y, 6 + inset, 10);
  fill(arms, y, 29, 33 - inset);
}

/** Outline + shading for one mask. */
function shadeLayer(mask: Mask, allShade = false): string[] {
  const at = (x: number, y: number) => x >= 0 && y >= 0 && x < SIZE && y < SIZE && mask[y][x];
  const rows: string[] = [];
  for (let y = 0; y < SIZE; y++) {
    let row = "";
    for (let x = 0; x < SIZE; x++) {
      if (!mask[y][x]) { row += "."; continue; }
      const edge = !at(x - 1, y) || !at(x + 1, y) || !at(x, y - 1) || !at(x, y + 1);
      if (edge) { row += "0"; continue; }
      const shade = allShade || !at(x + 1, y) || !at(x, y + 1) || x >= 27 || y >= 31;
      const light = (x - 15) ** 2 + (y - 14) ** 2 <= 3 || (x === 13 && y === 17) || (x === 12 && y === 18);
      row += shade ? "2" : light ? "3" : "1";
    }
    rows.push(row);
  }
  return rows;
}

const stack = (layers: string[][]) =>
  layers[0].map((_, y) =>
    Array.from({ length: SIZE }, (_, x) => {
      for (let i = layers.length - 1; i >= 0; i--) if (layers[i][y][x] !== ".") return layers[i][y][x];
      return ".";
    }).join(""),
  );

const armRows = shadeLayer(arms);
const rows = stack([shadeLayer(feet, true), armRows, shadeLayer(body)]);

// The right arm (x >= 30) is redrawn over the weapon so the Pingo "holds" it.
const hand = armRows.map((row, y) =>
  row.split("").map((c, x) => (x >= 30 && y >= 23 && y <= 26 ? c : ".")).join(""),
);

const out = `// GENERATED by scripts/generate-base-sprite.ts — safe to hand-edit.
// Legend: '.' empty, '0' outline, '1' body, '2' shade, '3' highlight
export const BODY_ROWS: string[] = [
${rows.map((r) => `  "${r}",`).join("\n")}
];

export const HAND_ROWS: string[] = [
${hand.map((r) => `  "${r}",`).join("\n")}
];
`;
const target = join(process.cwd(), "src", "sprites", "data", "base.ts");
writeFileSync(target, out);
console.log("wrote", target);
console.log(rows.join("\n"));
