export type IconName = keyof typeof ICONS;

/** Symbols that stay as text even though an icon lists them (× is "times" in "2×" and "A × B"). */
const KEEP_AS_TEXT = new Set(["×", "🪙 (moeda)"]);

const normalize = (s: string) => s.replace(/️/g, "");

/** emoji/symbol → icon, used to swap emojis inside texts (also old texts saved in the database). */
export const EMOJI_ICON: Record<string, IconName> = Object.fromEntries(
  (Object.entries(ICONS) as [IconName, PixelIcon][]).flatMap(([name, icon]) =>
    icon.replaces.filter((e) => !KEEP_AS_TEXT.has(e)).map((e) => [normalize(e), name]),
  ),
);

/** Splits a text into plain parts and icon names, e.g. "🏆 Campeão" → [{icon:"trophy"}, " Campeão"]. */
export function splitEmoji(text: string): Array<string | { icon: IconName }> {
  const keys = Object.keys(EMOJI_ICON).sort((a, b) => b.length - a.length);
  const out: Array<string | { icon: IconName }> = [];
  let buffer = "";
  let i = 0;
  while (i < text.length) {
    const match = keys.find((k) => text.startsWith(k, i));
    if (match) {
      if (buffer) out.push(buffer);
      buffer = "";
      out.push({ icon: EMOJI_ICON[match] });
      i += match.length;
      if (text[i] === "️") i++;
    } else {
      buffer += text[i];
      i++;
    }
  }
  if (buffer) out.push(buffer);
  return out;
}
